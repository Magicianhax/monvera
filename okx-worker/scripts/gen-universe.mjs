// Builds src/universe.ts from Jupiter's token search (OKX's all-tokens list
// does not index xStocks even though its aggregator quotes them — probe 3).
// Run: node scripts/gen-universe.mjs
import { writeFileSync } from "node:fs";

const WANTED = [
  // basket tickers + liquid extras; each queried as "<TICKER>x"
  "AAPL", "MSFT", "NVDA", "GOOGL", "AMZN", "META", "TSLA", "AVGO", "TSM", "AMD",
  "QCOM", "LLY", "ASML", "XOM", "JNJ", "PG", "KO", "MCD", "PEP", "SPY", "QQQ",
  "INTC", "PLTR", "COIN", "HOOD", "GLD", "CRCL", "MSTR", "UNH", "V", "WMT",
  "JPM", "NFLX", "ORCL", "CRM", "ABT", "AZN", "NVO", "PFE", "MRK", "CSCO",
];

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const byMint = new Map();

async function search(query) {
  try {
    const res = await fetch(
      `https://lite-api.jup.ag/tokens/v2/search?query=${encodeURIComponent(query)}`
    );
    if (!res.ok) return [];
    const data = await res.json();
    return Array.isArray(data) ? data : data.tokens ?? [];
  } catch {
    return [];
  }
}

function take(tokens) {
  for (const t of tokens) {
    const symbol = t.symbol ?? "";
    const name = t.name ?? "";
    const mint = t.id ?? t.address;
    if (!mint) continue;
    if (!/^[A-Z.]{1,6}x$/.test(symbol)) continue;
    if (!/xstock/i.test(name)) continue;
    // Genuine Backed xStocks mints carry the "Xs" vanity prefix; everything
    // else matching the name pattern is a copycat token. Keep one per symbol.
    if (!mint.startsWith("Xs")) continue;
    if ([...byMint.values()].some((t) => t.symbol === symbol)) continue;
    byMint.set(mint, { symbol, name, mint });
  }
}

take(await search("xstock"));
for (const ticker of WANTED) {
  if ([...byMint.values()].some((t) => t.symbol === `${ticker}x`)) continue;
  await sleep(300);
  take(await search(`${ticker}x`));
}

const ETFS = new Set(["SPY", "QQQ", "GLD"]);
const assets = [...byMint.values()]
  .map((r) => ({
    symbol: r.symbol,
    name: r.name.replace(/\s*xstock\s*/i, " ").trim(),
    underlying: r.symbol.replace(/x$/, ""),
    mint: r.mint,
    kind: ETFS.has(r.symbol.replace(/x$/, "")) ? "etf" : "stock",
  }))
  .sort((a, b) => a.symbol.localeCompare(b.symbol));

writeFileSync(
  new URL("../src/universe.ts", import.meta.url),
  `// GENERATED by scripts/gen-universe.mjs (2026-07-19) — hand-curated, kept in git.\n` +
    `// Source: Jupiter token search; validated tradability via OKX DEX quotes at runtime.\n` +
    `export type XAsset = {\n` +
    `  symbol: string;\n` +
    `  name: string;\n` +
    `  underlying: string;\n` +
    `  mint: string;\n` +
    `  kind: "stock" | "etf";\n` +
    `};\n\n` +
    `export const USDC_SOL_MINT = "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v";\n\n` +
    `export const UNIVERSE: XAsset[] = ${JSON.stringify(assets, null, 2)};\n\n` +
    `export function assetBySymbol(symbol: string): XAsset | undefined {\n` +
    `  const s = symbol.toLowerCase();\n` +
    `  return UNIVERSE.find((a) => a.symbol.toLowerCase() === s || a.underlying.toLowerCase() === s);\n` +
    `}\n`
);
console.log(`wrote ${assets.length} assets:`, assets.map((a) => a.symbol).join(" "));
